self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((c) => c.addAll(APP_SHELL))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(names.filter((n) => n.startsWith('autoshorts-') && n !== CACHE && n !== RUNTIME).map((n) => caches.delete(n)));
      await self.clients.claim();
    })()
  );
});

function isolate(response) {
  if (!response || response.status === 0 || response.type === 'opaque') return response;
  const headers = new Headers(response.headers);
  headers.set('Cross-Origin-Opener-Policy', 'same-origin');
  headers.set('Cross-Origin-Embedder-Policy', 'credentialless');
  headers.set('Cross-Origin-Resource-Policy', 'same-origin');
  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // models, stock media and APIs go straight to the network
  if (req.cache === 'only-if-cached' && req.mode !== 'same-origin') return;

  if (req.mode === 'navigate') {
    // network first so updates arrive, cached copy when offline
    const isShell = /\/(index\.html)?$/.test(url.pathname);
    event.respondWith(
      (async () => {
        try {
          const fresh = await fetch(req);
          if (fresh.ok) {
            const cache = await caches.open(CACHE);
            cache.put(isShell ? './index.html' : req, fresh.clone()).catch(() => {});
          }
          return isolate(fresh);
        } catch {
          const cached = (await caches.match(req, { ignoreSearch: true })) || (isShell ? await caches.match('./index.html') : null);
          return isolate(cached || new Response('You are offline.', { status: 503, headers: { 'Content-Type': 'text/plain' } }));
        }
      })()
    );
    return;
  }

  event.respondWith(
    (async () => {
      const cached = (await caches.match(req, { ignoreSearch: true })) || (await caches.open(RUNTIME).then((c) => c.match(req)));
      if (cached) return isolate(cached);
      try {
        const res = await fetch(req);
        if (res.ok && (url.pathname.includes('/vendor/') || url.pathname.includes('/fonts/') || url.pathname.includes('/icons/'))) {
          const c = await caches.open(RUNTIME);
          c.put(req, res.clone()).catch(() => {});
        }
        return isolate(res);
      } catch (e) {
        return new Response('', { status: 504, statusText: 'Offline' });
      }
    })()
  );
});
